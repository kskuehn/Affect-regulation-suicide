# =============================================================================
# config.R — single place to choose the data source and sampler settings
# =============================================================================
# Every script sources this file. Change settings here, not in the scripts.

CONFIG <- list(
  # "public" (default) reads the de-identified analysis files in data/public/, which reproduce
  # the published results. "redcap" reads the private files built from the REDCap exports by
  # R/00_import_redcap.R and R/00_import_inperson.R (study team only; see data/README.md).
  data_source = Sys.getenv("PRECISE_DATA", "public"),

  # SI outcome. Primary (manuscript): "intent_suicide_now" = "What is your intention to kill
  # yourself in this moment?" > 0 (asked only when the screener "thought about hurting or killing
  # yourself" = Yes; otherwise coded 0). Alternatives: "si_any" (the screener itself) or
  # "intent_suicide_30m". Each definition writes to its own output folder.
  si_definition = Sys.getenv("PRECISE_SI", "intent_suicide_now"),

  raw_dir       = "data/raw",
  derived_dir   = "data/derived",
  # Results go to output_<data_source>[_<si_definition>]/ (git-ignored; regenerated by the pipeline).
  out_dir       = NA,

  # Sampler settings. FAST=1 is for checking the pipeline end-to-end;
  # use the defaults (FAST unset) for any numbers that go into the paper.
  fast   = Sys.getenv("FAST", "0") == "1",
  chains = 4,
  iter   = 4000,
  warmup = 2000,
  cores  = max(1, min(4, parallel::detectCores())),
  seed   = 20261027,
  adapt_delta = 0.95,

  # Treatment-study settings
  early_window_days = 14,   # "early coupling" = first 2 weeks of EMA
  late_window_days  = 14,   # "late" window for change scores = last 2 weeks
  max_lag_hours     = 6     # lagged models: only pair prompts <= this far apart, same day
)

# data_source: "public" (data/public) | "redcap" (private; built by R/00_import_*.R) | "real" (data/raw/ema_long.csv)
CONFIG$src_dir     <- switch(CONFIG$data_source, public = "data/public", real = CONFIG$raw_dir,
                             redcap = file.path(CONFIG$raw_dir, "from_redcap"),
                             stop("PRECISE_DATA must be public, redcap or real"))
CONFIG$out_dir     <- paste0("output_", CONFIG$data_source)
suffix <- if (CONFIG$si_definition != "si_any") paste0("_", CONFIG$si_definition) else ""
CONFIG$out_dir     <- paste0(CONFIG$out_dir, suffix)
CONFIG$derived_dir <- file.path(CONFIG$derived_dir, paste0(CONFIG$data_source, suffix))
CONFIG$fits_dir    <- file.path(CONFIG$out_dir, "fits")
CONFIG$tables_dir  <- file.path(CONFIG$out_dir, "tables")
CONFIG$figures_dir <- file.path(CONFIG$out_dir, "figures")

if (CONFIG$fast) {
  CONFIG$chains <- 2
  CONFIG$iter   <- 1000
  CONFIG$warmup <- 500
}

for (d in CONFIG[c("derived_dir", "fits_dir", "tables_dir", "figures_dir")]) {
  dir.create(d, recursive = TRUE, showWarnings = FALSE)
}
